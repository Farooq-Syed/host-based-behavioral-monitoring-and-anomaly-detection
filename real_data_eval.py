"""Real-data evaluation of the comparative detection method.

monitor.py runs on a fixed 11-feature windowed schema generated by
generate_telemetry.py. To evaluate the *method* (not just that schema) on real labeled
telemetry — e.g. real Sysmon/EDR windows or a real feature frame — this script runs the
same comparative stack that monitor.py uses: IsolationForest + LOF (unsupervised) and a
RandomForest (supervised), combined by the same majority vote, on ANY numeric feature
frame with a label column.

Honest scoping:
  - Unsupervised methods use no labels (contamination only); the supervised model and the
    vote use the label. Unsupervised scores are therefore honestly optimistically-free.
  - Feature scaling is fit inside each training fold only (no leakage), matching
    monitor.py's methodology.
  - Input features are whatever numeric columns the real frame carries; this is NOT the
    same aggregate 11-feature model, so rules do not transfer — only the ML comparison does.

Usage:
  python real_data_eval.py --input data/<real_frame>.csv --label-column label
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import IsolationForest, RandomForestClassifier
from sklearn.metrics import f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import StratifiedKFold
from sklearn.neighbors import LocalOutlierFactor
from sklearn.preprocessing import StandardScaler

from monitor import normalize_label


def load_frame(path: Path, label_column: str) -> tuple[pd.DataFrame, np.ndarray]:
    frame = pd.read_csv(path)
    if label_column not in frame.columns:
        raise ValueError(f"Label column '{label_column}' not found.")
    truth = frame[label_column].map(normalize_label).to_numpy(dtype=int)
    numeric = frame.drop(columns=[label_column]).select_dtypes(include=[np.number])
    if numeric.shape[1] < 2:
        raise ValueError("Need at least two numeric feature columns.")
    return numeric, truth


def evaluate(features: pd.DataFrame, truth: np.ndarray, folds: int, random_state: int,
             contamination: float) -> dict:
    splitter = StratifiedKFold(n_splits=folds, shuffle=True, random_state=random_state)
    agg = {name: {"f1": [], "precision": [], "recall": []} for name in ("iforest", "lof", "random_forest", "vote")}
    last_auc = 0.0

    for train_idx, test_idx in splitter.split(features, truth):
        x_train = features.iloc[train_idx].to_numpy(dtype=float)
        x_test = features.iloc[test_idx].to_numpy(dtype=float)
        y_train, y_test = truth[train_idx], truth[test_idx]
        # scale inside the fold only (no leakage)
        scaler = StandardScaler().fit(x_train)
        x_train_s = scaler.transform(x_train)
        x_test_s = scaler.transform(x_test)

        iforest = IsolationForest(n_estimators=200, contamination=contamination, random_state=random_state, n_jobs=-1)
        iforest.fit(x_train_s)
        pred_if = (iforest.predict(x_test_s) == -1).astype(int)

        lof = LocalOutlierFactor(n_neighbors=30, contamination=contamination, novelty=True)
        lof.fit(x_train_s)
        pred_lof = (lof.predict(x_test_s) == -1).astype(int)

        rf = RandomForestClassifier(n_estimators=300, class_weight="balanced", random_state=random_state, n_jobs=-1)
        rf.fit(x_train_s, y_train)
        pred_rf = rf.predict(x_test_s)
        prob_rf = rf.predict_proba(x_test_s)[:, 1]

        votes = pred_if + pred_lof + pred_rf
        pred_vote = (votes >= 2).astype(int)

        for name, pred in (("iforest", pred_if), ("lof", pred_lof),
                           ("random_forest", pred_rf), ("vote", pred_vote)):
            agg[name]["f1"].append(f1_score(y_test, pred, zero_division=0))
            agg[name]["precision"].append(precision_score(y_test, pred, zero_division=0))
            agg[name]["recall"].append(recall_score(y_test, pred, zero_division=0))
        last_auc = roc_auc_score(y_test, prob_rf)

    out = {}
    for name, scores in agg.items():
        out[name] = {
            "f1_mean": round(float(np.mean(scores["f1"])), 4),
            "f1_std": round(float(np.std(scores["f1"])), 4),
            "precision": round(float(np.mean(scores["precision"])), 4),
            "recall": round(float(np.mean(scores["recall"])), 4),
        }
    out["auc_random_forest"] = round(float(last_auc), 4)
    return {"method": "comparative (IF + LOF + RF, majority vote)",
            "folds": folds, "rows": int(len(truth)), "attacks": int(truth.sum()),
            "metrics": out}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True)
    ap.add_argument("--label-column", default="label")
    ap.add_argument("--folds", type=int, default=5)
    ap.add_argument("--random-state", type=int, default=42)
    ap.add_argument("--contamination", type=float, default=0.2)
    ap.add_argument("--metrics-output", default="")
    args = ap.parse_args()

    features, truth = load_frame(Path(args.input), args.label_column)
    result = evaluate(features, truth, args.folds, args.random_state, args.contamination)
    print(json.dumps(result, indent=2))

    if args.metrics_output:
        out = Path(args.metrics_output)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps({"input": args.input, **result}, indent=2), encoding="utf-8")
        print(f"\nSaved -> {out}")


if __name__ == "__main__":
    main()
